def build_user(grade: int, topic: str | None, text: str) -> str:
    lines = [f"[학년] 초등 {grade}학년"]
    if topic and topic.strip():
        lines.append(f"[문제] {topic.strip()}")
    lines += ["[학생 글]", text.strip()]
    return "\n".join(lines)
