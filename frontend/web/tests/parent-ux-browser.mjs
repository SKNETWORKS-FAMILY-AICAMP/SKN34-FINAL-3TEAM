import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const base = process.env.DEMO_URL ?? 'http://127.0.0.1:5185'
const out = '.taste-skill/parent-ux-548'
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
await context.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//, r => r.abort())
const page = await context.newPage(), errors = [], checks = []
context.on('page', p => p.on('pageerror', e => errors.push(e.message)))
page.on('pageerror', e => errors.push(e.message))
page.setDefaultTimeout(15000)
try {
 await page.goto(base + '/login')
 await page.getByLabel('이메일', { exact: true }).fill('parent@example.test')
 await page.getByLabel('비밀번호', { exact: true }).fill('demo-only')
 await page.getByRole('button', { name: '시연 계정으로 로그인' }).click()
 await page.waitForURL(/parent\/journal/)
 await page.getByRole('heading', { name: '서윤의 학습 현황' }).waitFor()
 const search = new URL(page.url()).search
 for (const width of [1440,768,390]) {
  await page.setViewportSize({ width, height: 900 })
  for (const [path,heading] of [['journal','서윤의 학습 현황'],['report','리포트·AI 챗봇'],['devices','기기·PIN'],['settings?section=sharing','계정·자녀 설정'],['billing','이용권·결제'],['help','이용 도움말'],['support','문의·오류 신고']]) {
   const url = new URL('/parent/'+path, base)
   new URLSearchParams(search).forEach((v,k) => url.searchParams.set(k,v))
   await page.goto(url.href)
   await page.getByRole('heading', { name: heading, exact: true }).waitFor()
   await page.locator('.ws-parent').waitFor()
   const floating = await page.locator('.ws-topbar-card').boundingBox()
   assert.ok(floating.x > 0 && floating.x + floating.width < width, 'top bar must have side gutters')
   assert.equal(floating.y,0, 'top bar must touch the top viewport edge')
   assert.equal(await page.locator('.ws-side .ws-plan').count(),0)
   assert.equal(await page.locator('.ws-parent-topbar .ws-demo').count(),0)
   const canvas = await page.locator('.ws-main').boundingBox()
   assert.ok(floating.x+floating.width > canvas.x+canvas.width, 'top bar must extend beyond canvas edge')
   assert.equal(await page.locator('.ws-parent-topbar').evaluate(el => getComputedStyle(el).backgroundColor),'rgba(0, 0, 0, 0)')
   const curve = await page.locator('.ws-topbar-card').evaluate(el => parseFloat(getComputedStyle(el).borderRadius))
   assert.ok(canvas.x >= floating.x+curve, 'canvas left must fit inside flat top bar span')
   assert.ok(canvas.x+canvas.width <= floating.x+floating.width-curve, 'canvas right must fit inside flat top bar span')
   assert.ok(await page.locator('.ws-topbar-card').evaluate(el => parseFloat(getComputedStyle(el).borderRadius) >= 24))
   assert.equal(await page.getByRole('button', { name:/이 자녀로 학습/ }).count(),0)
   assert.equal(await page.locator('.ws-header .app-brand').count(),1)
   const bell = await page.getByRole('button', { name:'알림 열기', exact:true }).boundingBox()
   const brand = await page.locator('.ws-top-brand .app-brand').boundingBox()
   assert.ok(bell.x >= brand.x + brand.width, 'notification must be right of the logo')
   const logout = await page.locator('.ws-header .ws-logout').boundingBox()
   assert.ok(logout.x > bell.x, 'logout must follow the notification')
   assert.equal(await page.locator('.ws-parent').evaluate(el => getComputedStyle(el).backgroundColor),'rgb(39, 112, 68)')
   if (path === 'report') {
    await page.getByRole('button', { name:'리포트 상세 보기', exact:true }).first().click()
    const toolbar = page.locator('.parent-report-toolbar')
    await toolbar.waitFor()
    const buttons = await toolbar.locator('button').all()
    assert.equal(buttons.length,3)
    const boxes = await Promise.all(buttons.map(b => b.boundingBox()))
    assert.ok(Math.max(...boxes.map(b=>b.width))-Math.min(...boxes.map(b=>b.width))<2)
   }
   if (path.startsWith('settings')) {
    const detail = page.locator('.parent-consent-document').first()
    await detail.waitFor(); await detail.locator('summary').click()
    assert.ok((await detail.locator('.parent-document-body').innerText()).length > 10)
   }
   await page.screenshot({ path: `${out}/${path.split('?')[0]}-${width}.png`, fullPage: true })
   if (width === 1440 && ['devices','help','billing'].includes(path)) {
    const html = await page.evaluate(async () => {
     const doc = document.documentElement.cloneNode(true)
     doc.querySelectorAll('script,link[rel="modulepreload"]').forEach(n => n.remove())
     for (const img of doc.querySelectorAll('img')) {
      const source = new URL(img.getAttribute('src'), location.href)
      if (source.origin !== location.origin) continue
      const blob = await (await fetch(source)).blob()
      const data = await new Promise(resolve => { const r = new FileReader(); r.onload = () => resolve(r.result); r.readAsDataURL(blob) })
      img.setAttribute('src',data)
     }
     return '<!doctype html>'+doc.outerHTML
    })
    await writeFile(`${out}/${path}.html`,html)
   }
   const size = await page.evaluate(() => ({ body: document.documentElement.scrollWidth, width: innerWidth }))
   assert.ok(size.body <= size.width+1, `${path} ${width}: horizontal overflow ${size.body}`)
   if (width === 1440) {
    const sidebar = page.locator('.ws-side')
    const header = await page.locator('.ws-parent-topbar').boundingBox()
    const side = await sidebar.boundingBox()
    assert.ok(side.x >= floating.x,'sidebar must sit within the wider top bar edge')
    assert.ok(side.width < 200,'sidebar must be narrower')
    assert.ok(side.y >= header.y+header.height-1, 'sidebar must start below top bar')
    assert.ok(side.height+header.height <= 901, 'sidebar and top bar must fit viewport')
    const before = await sidebar.boundingBox(); await page.evaluate(() => scrollTo(0,document.body.scrollHeight))
    const after = await sidebar.boundingBox(); assert.ok(Math.abs(before.y-after.y)<2, path+' sidebar moved')
    await page.evaluate(() => scrollTo(0,0))
   } else {
    await page.getByRole('button', { name: '학부모 메뉴 열기', exact: true }).click()
    await page.getByRole('dialog').getByRole('link', { name: '기기·PIN', exact: true }).waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await page.getByRole('dialog').count(),0)
   }
   checks.push(`${path} ${width}`)
  }
  const selectStyle = await page.locator('.ws-header select').evaluate(el => {
   const style = getComputedStyle(el)
   return { appearance:style.appearance, right:parseFloat(style.paddingRight), arrow:style.backgroundPosition }
  })
  assert.equal(selectStyle.appearance,'base-select')
  assert.ok(selectStyle.right >= 42)
  assert.match(selectStyle.arrow,/14px/)
  const childDropdown = page.locator('.ws-header select')
  const picker = await childDropdown.evaluate(el => {
   const panel = getComputedStyle(el,'::picker(select)'), selected = getComputedStyle(el.selectedOptions[0])
   return { radius:panel.borderRadius, background:selected.backgroundColor, text:selected.color }
  })
  assert.equal(picker.radius,'14px')
  assert.equal(picker.background,'rgb(39, 112, 68)')
  assert.equal(picker.text,'rgb(255, 255, 255)')
  await childDropdown.click()
  await page.screenshot({ path:`${out}/dropdown-menu-${width}.png`,fullPage:false })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name:'알림 열기', exact:true }).click()
  const dialog = page.getByRole('dialog', { name:'알림', exact:true })
  const toolbar = dialog.locator('.notification-toolbar')
  await toolbar.waitFor()
  const checkLabel = await toolbar.locator('.ws-check').boundingBox()
  const checkbox = await toolbar.getByRole('checkbox').boundingBox()
  assert.ok(Math.abs(checkLabel.y+checkLabel.height/2-checkbox.y-checkbox.height/2)<1.5)
  const bulk = await Promise.all((await toolbar.getByRole('button').all()).map(b=>b.boundingBox()))
  assert.ok(Math.abs(bulk[0].y+bulk[0].height/2-bulk[1].y-bulk[1].height/2)<1.5)
  const pager = dialog.getByRole('navigation', { name:'알림 페이지', exact:true })
  const cells = await pager.locator(':scope > *').evaluateAll(es=>es.map(el=> { const b=el.getBoundingClientRect();return b.y+b.height/2 }))
  assert.ok(Math.max(...cells)-Math.min(...cells)<1.5)
  const close = dialog.getByRole('button', { name:'창 닫기', exact:true })
  const closeBox = await close.boundingBox(), icon = await close.locator('svg').boundingBox()
  assert.equal(closeBox.width,closeBox.height)
  assert.ok(Math.abs(closeBox.x+closeBox.width/2-icon.x-icon.width/2)<1.5)
  assert.ok(Math.abs(closeBox.y+closeBox.height/2-icon.y-icon.height/2)<1.5)
  await page.screenshot({ path:`${out}/notification-alignment-${width}.png`,fullPage:false })
  await page.keyboard.press('Escape')
  checks.push(`notification controls and dropdown alignment ${width}`)
 }
 await page.setViewportSize({ width: 1440, height: 480 })
 const sideScroll = page.locator('.ws-side')
 const sidebarState = await sideScroll.evaluate(el => {
  el.scrollTop = 100
  return { top:el.scrollTop, overflow:getComputedStyle(el).overflowY, position:getComputedStyle(el).position }
 })
 assert.equal(sidebarState.top,0)
 assert.equal(sidebarState.overflow,'visible')
 assert.equal(sidebarState.position,'static')
 await page.locator('.ws-side .ws-support a').last().scrollIntoViewIfNeeded()
 await page.screenshot({ path:`${out}/sidebar-no-scroll.png`,fullPage:false })
 checks.push('sidebar has no independent scroll; short viewport uses page flow')
 await page.setViewportSize({ width: 1440, height: 900 })
 await page.goto(base+'/parent/billing'+search)
 await page.getByRole('button', { name: '무료 플랜으로 전환', exact: true }).click()
 await page.getByRole('dialog', { name: '자동 갱신 해지', exact: true }).waitFor()
 assert.match(await page.getByRole('dialog').innerText(), /이용할 수 있으며 다음 자동 청구를 중단/)
 await page.keyboard.press('Escape')
 const childSelect = page.getByLabel('자녀 선택', { exact: true })
 const options = await childSelect.locator('option').evaluateAll(os => os.map(o => ({ value:o.value, text:o.textContent })))
 const freeChild = options.find(o => o.text.includes('도윤'))
 assert.ok(freeChild)
 await childSelect.selectOption(freeChild.value)
 await page.getByRole('button', { name:'현재 무료 플랜', exact:true }).waitFor()
 await page.getByRole('radio').first().check()
 const requests=[]
 page.on('request', r => { if (r.method()==='POST' && new URL(r.url()).pathname==='/api/v1/orders') requests.push(r.url()) })
 await page.evaluate(() => { window.__savedOpen = window.open; window.open = () => null })
 await page.getByRole('button', { name:'결제수단 선택', exact:true }).click()
 await page.getByRole('alert').filter({ hasText:'팝업을 허용' }).waitFor()
 assert.equal(requests.length,0)
 await page.evaluate(() => { window.open=window.__savedOpen })
 const popupPromise = context.waitForEvent('page')
 await page.getByRole('button', { name:'결제수단 선택', exact:true }).click()
 const popup = await popupPromise
 await popup.getByRole('heading', { name:'결제수단 선택', exact:true }).waitFor()
 const pay = popup.getByRole('button', { name:'14,900원 결제하기', exact:true })
 await pay.waitFor()
 const pending = await popup.evaluate(() => sessionStorage.getItem('sagomungchi:checkout:v1'))
 await popup.reload()
 await pay.waitFor()
 assert.equal(await popup.evaluate(() => sessionStorage.getItem('sagomungchi:checkout:v1')),pending)
 await pay.click()
 await popup.getByRole('heading', { name:'모의 결제가 완료되었습니다', exact:true }).waitFor()
 assert.equal(await popup.evaluate(() => window.opener),null)
 assert.equal(requests.length,0, 'original tab must not create orders')
 await popup.screenshot({ path:`${out}/payment-complete.png`,fullPage:true })
 await page.getByRole('heading', { name:/프리미엄/ }).first().waitFor()
 await popup.close()
 checks.push('free plan confirmation', 'blocked popup creates no order', 'separate checkout and payment completion', 'checkout reload preserves order', 'payment updates original tab')
 const failed = await context.newPage()
 const approvals=[]
 failed.on('request', r => { if (r.method()==='POST' && r.url().includes('/payments/confirm')) approvals.push(r.url()) })
 await failed.goto(base+'/payment/fail?orderId=canceled-test')
 await failed.getByRole('heading', { name:'결제를 완료하지 못했습니다', exact:true }).waitFor()
 assert.equal(approvals.length,0)
 await failed.close()
 checks.push('canceled checkout does not confirm')
 assert.deepEqual(errors,[])
 await writeFile(`${out}/results.json`,JSON.stringify({ checks, errors },null,2))
 console.log(`PASS ${checks.length} responsive page checks; no page errors`)
} catch(e) { console.error((await page.locator('body').innerText()).slice(-3500)); throw e }
finally { await browser.close() }
