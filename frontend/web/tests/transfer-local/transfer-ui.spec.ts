import { test, expect, type Page, type BrowserContext, type Locator } from '@playwright/test'
import { actor, child, call, reauth, transfer, disposeActors, type Actor } from './api.ts'
import { useGoogleIdentity as installGoogleIdentity } from '../e2e/support/google.ts'
import { queueWeeklyReport } from '../e2e/support/db.ts'

test.afterEach(disposeActors)
async function login(context: BrowserContext, page: Page, who: Actor) {
  await installGoogleIdentity(context, who.identity)
  await page.goto('/login')
  await page.getByRole('link', { name: 'Google 계정으로 계속하기' }).click()
  await page.waitForURL('**/parent/**')
  await expect(page.getByRole('heading', { level: 1, name: /의 학습 기록$|^자녀 등록$/ })).toBeVisible()
}
async function proof(page: Page, dialog: Locator) {
  const popupEvent = page.waitForEvent('popup')
  await dialog.getByRole('button', { name: 'Google 본인 확인' }).click()
  const popup = await popupEvent
  await expect(popup.locator('body')).toContainText('VERIFIED', { timeout: 30_000 })
  await popup.close()
  await dialog.getByRole('button', { name: '완료 확인', exact: true }).click()
  await expect(dialog.getByText('재확인을 마쳤습니다.', { exact: false })).toBeVisible()
}

