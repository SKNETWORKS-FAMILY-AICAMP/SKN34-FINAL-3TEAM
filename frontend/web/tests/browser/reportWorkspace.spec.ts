test('weekly records keep reflection and quote in the selected activity @responsive',async({page},info)=>{
 await page.goto('/parent/report?reportDemo=structured&childId=demo-report-grade5&reportId=demo-report-grade5-2026-11-09')
 const modal=page.getByRole('dialog',{name:'리포트 예시의 학습 리포트'})
 await expect(modal).toBeVisible()
 await expect(modal.getByText('계산 근거',{exact:true})).toHaveCount(0)
 await expect(modal.locator('.report-count-list')).toContainText('전체 3건 중')
 await modal.getByRole('button',{name:'활동 기록',exact:true}).click()
 const picker=modal.getByRole('combobox',{name:'주간 리포트 활동 선택'})
 const category=modal.getByRole('combobox',{name:'주간 리포트 유형 선택'})
 await expect(category.locator('option')).toHaveCount(3)
 await category.selectOption('EVALUATE')
 await expect(picker.locator('option')).toHaveCount(1)
 await picker.selectOption('structured-report-demo-library')
 const pair=modal.locator('.weekly-activity-pair')
 await expect(pair).toContainText('멀리 간다고만 쓰지 않고')
 await expect(pair).toContainText('우리 동네에는 도서관이 필요하다')
 await expect(pair).not.toContainText('밤늦게까지 영상을')
 await category.selectOption('ANALYZE')
 await picker.selectOption('structured-report-demo-phone')
 await expect(pair).toContainText('좋은 점도 있다는 생각')
 await expect(pair).toContainText('밤늦게까지 영상을')
 await expect(pair).not.toContainText('우리 동네에는 도서관')
 await pair.scrollIntoViewIfNeeded();await page.screenshot({path:info.outputPath('weekly-selected-activity.png')})
 expect(await modal.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true)
})

 test('report date picker applies weeks and clears filters',async({page},info)=>{
 await page.goto('/parent/report?reportDemo=structured&childId=demo-report-grade5')
 await page.getByRole('button',{name:'리포트 자세히 보기',exact:false}).click()
 const modal=page.getByRole('dialog',{name:'리포트 예시의 학습 리포트'})
 await modal.getByRole('button',{name:'주간 날짜 선택',exact:true}).click()
 const calendar=modal.getByRole('group',{name:'날짜 선택'})
 await calendar.getByRole('button',{name:'2026-11-11',exact:true}).click()
 await expect(calendar.getByLabel('시작 날짜')).toHaveValue('2026-11-09')
 await expect(calendar.getByLabel('종료 날짜')).toHaveValue('2026-11-15')
 await calendar.scrollIntoViewIfNeeded();await page.screenshot({path:info.outputPath('calendar.png')})
 await calendar.getByRole('button',{name:'확인',exact:true}).click()
 await expect(modal.locator('.report-date-controls').first()).toContainText('2026-11-09 ~ 2026-11-15')
 await modal.getByRole('button',{name:'초기화',exact:true}).click()
 await modal.getByRole('button',{name:'일일 날짜 선택',exact:true}).click()
 await calendar.getByRole('button',{name:'하루',exact:true}).click()
 await calendar.getByLabel('시작 날짜').fill('2026-11-12')
 await calendar.getByRole('button',{name:'확인',exact:true}).click()
 await expect(modal.locator('.report-date-controls').last()).toContainText('2026-11-12 ~ 2026-11-12')
 })
