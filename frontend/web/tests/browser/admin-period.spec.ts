import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

async function overview(page: Page) {
  await page.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//, route => route.abort())
  await page.goto('/admin/login')
  await page.getByLabel('로그인 ID', { exact: true }).fill('admin@example.test')
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/home/)
  await page.getByLabel('집계 시작일', { exact: true }).fill('2026-11-01')
  await page.getByLabel('집계 종료일', { exact: true }).fill('2026-11-09')
  await page.getByRole('button', { name: '기간 적용', exact: true }).click()
  await expect(page).toHaveURL(/from=2026-11-01&to=2026-11-09/)
}

test('달력의 두 날짜는 확인 전까지 적용하지 않고 취소하면 유지한다 @responsive', async ({ page }, testInfo) => {
  await overview(page)
  const trigger = page.getByRole('button', { name: '집계 기간 달력 열기' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '집계 기간 선택' })
  await dialog.getByRole('button', { name: '2026년 11월 5일', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '확인', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '2026년 11월 17일', exact: true }).click()
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('status')).toHaveText('2026-11-05 ~ 2026-11-17')
  await expect(page).toHaveURL(/from=2026-11-01&to=2026-11-09/)
  const box = await dialog.boundingBox(), viewport = page.viewportSize()!
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(viewport.width)
  expect(box!.y + box!.height).toBeLessThanOrEqual(viewport.height)
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: testInfo.outputPath('range-selected.png') })
  await dialog.getByRole('button', { name: '취소', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(page.getByLabel('집계 시작일', { exact: true })).toHaveValue('2026-11-01')
  await trigger.click()
  await dialog.getByRole('button', { name: '2026년 11월 5일', exact: true }).click()
  await dialog.getByRole('button', { name: '2026년 11월 17일', exact: true }).click()
  await dialog.getByRole('button', { name: '확인', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page).toHaveURL(/from=2026-11-05&to=2026-11-17/)
  await expect(page.getByLabel('집계 종료일', { exact: true })).toHaveValue('2026-11-17')
  await expect(trigger).toBeFocused()
  await page.screenshot({ path: testInfo.outputPath('period-applied.png') })
})

test('월 경계·역순 선택·같은 날을 지원하고 Escape는 선택을 취소한다 @responsive', async ({ page }) => {
  await overview(page)
  const trigger = page.getByRole('button', { name: '집계 기간 달력 열기' })
  const dialog = page.getByRole('dialog', { name: '집계 기간 선택' })
  await trigger.click()
  await dialog.getByRole('button', { name: '2026년 11월 3일', exact: true }).click()
  await dialog.getByRole('button', { name: '이전 달', exact: true }).click()
  await dialog.getByRole('button', { name: '2026년 10월 28일', exact: true }).click()
  await expect(dialog.getByRole('status')).toHaveText('2026-10-28 ~ 2026-11-03')
  await dialog.getByRole('button', { name: '확인', exact: true }).click()
  await expect(page).toHaveURL(/from=2026-10-28&to=2026-11-03/)
  await trigger.click()
  await dialog.getByRole('button', { name: '2026년 10월 31일', exact: true }).click()
  await page.keyboard.press('ArrowRight')
  await expect(dialog.getByRole('button', { name: '2026년 11월 1일', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(dialog.getByRole('status')).toHaveText('2026-10-31 ~ 2026-11-01')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(page).toHaveURL(/from=2026-10-28&to=2026-11-03/)
  await trigger.click()
  await dialog.getByRole('button', { name: '2026년 10월 28일', exact: true }).click()
  await dialog.getByRole('button', { name: '2026년 10월 28일', exact: true }).click()
  await dialog.getByRole('button', { name: '확인', exact: true }).click()
  await expect(page).toHaveURL(/from=2026-10-28&to=2026-10-28/)
})

test('날짜 직접 입력은 실제 날짜와 순서를 확인하고 잘못된 기간을 조회하지 않는다 @responsive', async ({ page }) => {
  await overview(page)
  const from = page.getByLabel('집계 시작일', { exact: true }), to = page.getByLabel('집계 종료일', { exact: true })
  await from.fill('2026-02-30')
  await page.getByRole('button', { name: '기간 적용', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('YYYY-MM-DD')
  await expect(page).toHaveURL(/from=2026-11-01&to=2026-11-09/)
  await from.fill('2026-11-18'); await to.fill('2026-11-01')
  await page.getByRole('button', { name: '기간 적용', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('순서')
  await from.fill('2026-11-10'); await to.fill('2026-11-18'); await to.press('Enter')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page).toHaveURL(/from=2026-11-10&to=2026-11-18/)
})

test('기간 적용 직후 새로 입력한 날짜는 URL 반영에 덮어쓰이지 않는다 @responsive', async ({ page }) => {
  await overview(page)
  const from = page.getByLabel('집계 시작일', { exact: true })
  // CI에서 발생한 URL 변경과 React 렌더 사이의 입력을 시간 지연 없이 재현한다.
  await page.evaluate(() => {
    const pushState = history.pushState
    history.pushState = function (...args: Parameters<History['pushState']>) {
      pushState.apply(this, args)
      history.pushState = pushState
      const input = document.querySelector<HTMLInputElement>('input[aria-label="집계 시작일"]')!
      Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, '2026-02-30')
      input.dispatchEvent(new Event('input', { bubbles: true }))
    }
  })
  await from.fill('2026-11-02')
  await page.getByRole('button', { name: '기간 적용', exact: true }).click()
  await expect(page).toHaveURL(/from=2026-11-02&to=2026-11-09/)
  await expect(from).toHaveValue('2026-02-30')
  await page.getByRole('button', { name: '기간 적용', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('YYYY-MM-DD')
  await expect(page).toHaveURL(/from=2026-11-02&to=2026-11-09/)
  // 뒤로 가기처럼 외부에서 기간이 바뀌면 입력과 오류도 그 기간으로 초기화한다.
  await page.goBack()
  await expect(page).toHaveURL(/from=2026-11-01&to=2026-11-09/)
  await expect(from).toHaveValue('2026-11-01')
  await expect(page.getByRole('alert')).toHaveCount(0)
})
