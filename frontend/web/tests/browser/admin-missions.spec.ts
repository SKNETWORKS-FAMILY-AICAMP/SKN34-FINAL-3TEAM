import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//, route => route.abort())
  await page.goto('/admin/login')
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/home/)
})

test('미션 초안: 성취기준·성취수준 고르기 → 요청 → 검사 통과 → 채택해 미션 편집 (#356)', async ({ page }) => {
  await page.getByRole('link', { name: '미션 초안', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/mission-drafts/)
  // 기존 초안: 검사 실패 사유와 시도 횟수
  await page.getByRole('row').filter({ hasText: '검사 실패' }).getByRole('button', { name: /초안 열기/ }).click()
  const failures = page.getByRole('region', { name: '검사 실패 사유' })
  await expect(failures).toContainText('질문 길이: 질문이 너무 김')
  await expect(failures).toContainText('요소 code')
  await expect(page.getByText('3/3회 (AI 호출 실패 포함)')).toBeVisible()

  await page.getByRole('button', { name: '초안 요청', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '성취기준을 1개 이상' })).toBeVisible()
  await page.getByLabel('성취기준 학년군', { exact: true }).selectOption('초5~6')
  await page.getByLabel('성취기준 검색어', { exact: true }).fill('6국01')
  await page.getByRole('button', { name: '성취기준 조회', exact: true }).click()
  await page.getByRole('button', { name: '6국01-02 고르기', exact: true }).click()
  await expect(page.getByLabel('성취수준 6국01-02', { exact: true }).locator('option')).toHaveText(['고르지 않음', 'A', 'B', 'C'])
  await page.getByLabel('성취수준 6국01-02', { exact: true }).selectOption('B')
  await page.getByLabel('초안 생각 유형', { exact: true }).selectOption('EVALUATE')
  await page.getByLabel('초안 최소 학년', { exact: true }).fill('5')
  await page.getByLabel('초안 최대 학년', { exact: true }).fill('6')
  await page.getByRole('button', { name: '초안 요청', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '초안을 요청했습니다.' })).toBeVisible()
  await expect(page.getByRole('region', { name: '초안 내용' })).toContainText('EVALUATE_PERSPECTIVE', { timeout: 15_000 })
  await page.getByRole('button', { name: '채택해 미션 편집', exact: true }).click()

  await expect(page).toHaveURL(/\/admin\/missions\?missionId=/)
  await expect(page.getByRole('heading', { name: '미션 작성·검토', exact: true })).toBeVisible()
  await expect(page.getByText(/LLM 초안 채택 · 작성 중/)).toBeVisible()
  await expect(page.getByRole('note', { name: '검토 안내' })).toContainText('6국01-02 · 초5~6')
  await expect(page.getByRole('note', { name: '검토 안내' })).toContainText('성취수준 B')
  await expect(page.getByLabel('요소 1 종류', { exact: true })).toHaveValue('COMMON')
  await expect(page.getByLabel('요소 1 코드', { exact: true })).toHaveValue('EVALUATE_CLAIM')
  await expect(page.getByLabel('요소 1 연결 성취기준', { exact: true })).toHaveValue('6국01-02')

  // 세 공통 요소를 다 쓰면 새 요소는 성취기준 고유 요소 e1
  await page.getByRole('button', { name: '기준표 요소 추가', exact: true }).click()
  await expect(page.getByLabel('요소 4 종류', { exact: true })).toHaveValue('UNIQUE')
  await expect(page.getByLabel('요소 4 코드', { exact: true })).toHaveValue('e1')
  await page.getByLabel('요소 4 이름', { exact: true }).fill('급식 투표 사례')
  await page.getByLabel('요소 4 코드', { exact: true }).fill('사례')
  await page.getByRole('button', { name: '새 기준표 버전 저장', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '요소 4: code 사례는' })).toBeVisible()
  await page.getByLabel('요소 4 코드', { exact: true }).fill('e1')
  await page.getByLabel('요소 4 연결 성취기준', { exact: true }).selectOption('6국01-02')
  await page.getByRole('button', { name: '새 기준표 버전 저장', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '새 기준표 버전을 저장했습니다.' })).toBeVisible()
  await expect(page.getByRole('list', { name: '게시 전 확인' })).toHaveText('현재 버전 검토 승인')
})

test('미션 편집: 성취기준 표에서 고르기·빼기와 요소 종류로 code 고르기 (#262·#356)', async ({ page }) => {
  await page.goto('/admin/missions?missionId=content-1')
  await expect(page.getByRole('heading', { name: '미션 작성·검토', exact: true })).toBeVisible()
  const picked = page.getByRole('list', { name: '고른 성취기준' })
  await expect(picked).toContainText('4과03-01')
  await expect(page.getByLabel('성취수준 4과03-01', { exact: true })).toHaveValue('B')
  await expect(page.getByLabel('요소 1 종류', { exact: true })).toHaveValue('UNIQUE')
  await page.getByLabel('요소 1 종류', { exact: true }).selectOption('COMMON')
  await expect(page.getByLabel('요소 1 코드', { exact: true })).toHaveValue('ANALYZE_RELATION')
  await page.getByRole('button', { name: '4과03-01 빼기', exact: true }).click()
  await expect(picked).not.toContainText('4과03-01')
  await page.getByLabel('성취기준 검색어', { exact: true }).fill('4과03-02')
  await page.getByRole('button', { name: '성취기준 조회', exact: true }).click()
  await page.getByRole('button', { name: '4과03-02 고르기', exact: true }).click()
  await page.getByRole('button', { name: '새 미션 버전 저장', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '새 버전을 저장했습니다.' })).toBeVisible()
  await expect(page.getByRole('list', { name: '게시 전 확인' })).toContainText('요소 연결 성취기준')
})
