import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

async function openFamily(page: Page) {
  await page.goto('/login')
  await page.getByRole('button', { name: '시연 계정으로 로그인', exact: true }).click()
  await expect(page).toHaveURL(/parent\/journal/)
  await page.goto('/parent/settings?childId=demo-seoyun')
  await expect(page.getByRole('region', { name: '우리 가족' })).toBeVisible()
}

test('family cards keep the selected Mungchi after reload and cancel unsaved choices @responsive', async ({ page }, info) => {
  await openFamily(page)
  const card = page.getByRole('article', { name: '서윤 자녀 카드' })
  const first = await card.locator('svg[data-friend]').getAttribute('data-friend')
  await page.reload()
  await expect(card.locator('svg[data-friend]')).toHaveAttribute('data-friend', first!)
  const bounds = await page.locator('.family-members').boundingBox()
  const panel = await page.locator('.parent-settings').boundingBox()
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(panel!.x + panel!.width + 1)
  await page.screenshot({ path: info.outputPath('family-cards.png'), fullPage: true })
  await card.getByRole('button', { name: '서윤 프로필 설정' }).click()
  const dialog = page.getByRole('dialog', { name: '서윤 프로필 설정' })
  await expect(dialog.getByRole('group', { name: '프로필 뭉치 선택' }).getByRole('button')).toHaveCount(12)
  await dialog.getByRole('button', { name: '별뭉치', exact: true }).click()
  await dialog.getByRole('button', { name: '뭉치 저장', exact: true }).click()
  await expect(dialog.getByRole('status')).toHaveText('프로필 뭉치를 저장했습니다.')
  const closeBox = await dialog.getByRole('button', { name: '창 닫기', exact: true }).boundingBox()
  expect(closeBox!.y).toBeGreaterThanOrEqual(0)
  await page.screenshot({ path: info.outputPath('family-character-picker.png') })
  await page.keyboard.press('Escape')
  await expect(card.getByRole('button', { name: '서윤 프로필 설정' })).toBeFocused()
  await expect(card.locator('svg[data-friend]')).toHaveAttribute('data-friend', 'star')
  await page.reload()
  await expect(card.locator('svg[data-friend]')).toHaveAttribute('data-friend', 'star')
  await card.getByRole('button', { name: '서윤 프로필 설정' }).click()
  await dialog.getByRole('button', { name: '눈뭉치', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(card.locator('svg[data-friend]')).toHaveAttribute('data-friend', 'star')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('family gear edits the intended child and preserves guardian and consent routes @responsive', async ({ page }, info) => {
  await openFamily(page)
  await page.getByRole('button', { name: '도윤 프로필 설정' }).click()
  const dialog = page.getByRole('dialog', { name: '도윤 프로필 설정' })
  await dialog.getByRole('button', { name: '자녀 정보', exact: true }).click()
  await expect(dialog.getByRole('heading', { name: '도윤의 프로필' })).toBeVisible()
  await expect(dialog.getByRole('heading', { name: '보호자 정보', exact: true })).toHaveCount(0)
  await dialog.getByLabel('새 자녀 별명', { exact: true }).fill('도윤 새별명')
  await dialog.getByRole('button', { name: '뭉치 변경', exact: true }).click()
  await expect(dialog.getByLabel('새 자녀 별명', { exact: true })).toBeHidden()
  await dialog.getByRole('button', { name: '자녀 정보', exact: true }).click()
  await expect(dialog.getByLabel('새 자녀 별명', { exact: true })).toHaveValue('도윤 새별명')
  const mutation = page.waitForRequest(r => r.url().endsWith('/api/v1/children/demo-doyun') && r.method() === 'PATCH')
  await dialog.getByRole('button', { name: '자녀 정보 저장' }).click()
  expect((await mutation).postDataJSON()).toEqual({ nickname: '도윤 새별명' })
  await expect(page.getByRole('status').filter({ hasText: '자녀 정보를 저장했습니다.' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('family-profile-form.png') })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('article', { name: '도윤 새별명 자녀 카드' })).toBeVisible()
  await expect(page.getByRole('article', { name: '서윤 자녀 카드' })).toBeVisible()
  await page.getByRole('button', { name: '보호자 정보 설정' }).click()
  await expect(page.getByRole('dialog').getByRole('heading', { name: '보호자 정보', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('tab', { name: '공개·동의', exact: true }).click()
  await expect(page.getByRole('heading', { name: '동의 이력·철회' })).toBeVisible()
  await page.getByRole('tab', { name: '프로필', exact: true }).click()
  await page.getByRole('button', { name: /자녀 추가 등록/ }).click()
  await expect(page.getByRole('dialog', { name: '자녀 프로필 등록' })).toBeVisible()
})
