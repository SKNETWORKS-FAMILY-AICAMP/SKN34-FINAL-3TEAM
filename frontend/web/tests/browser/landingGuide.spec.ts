import { expect, test } from '@playwright/test'

test('공개 이용 안내와 약관을 로그인 없이 읽고 닫는다 @responsive', async ({ page }) => {
  await page.goto('/')
  const trigger = page.getByRole('button', { name: '이용 안내', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '이용 안내', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('h3').first()).toHaveText('약관 및 개인정보')
  await expect(page).toHaveURL(/\/$/)
  const category = dialog.locator('.lp-guide-section').filter({ hasText: '처음 시작하기' })
  await expect(category).not.toHaveAttribute('open', '')
  await category.locator(':scope > summary').click()
  const question = category.locator('summary').filter({ hasText: '학생은 어떻게 로그인하나요?' })
  const beforeQuestion = await question.locator('span').boundingBox()
  await question.click()
  const afterQuestion = await question.locator('span').boundingBox()
  expect(afterQuestion!.x).toBeCloseTo(beforeQuestion!.x, 1)
  const answer = await category.locator('.lp-guide-item[open] .lp-guide-answer').boundingBox()
  expect(answer!.y).toBeGreaterThan(afterQuestion!.y + afterQuestion!.height)

  await expect(category.getByText('학부모 화면의 기기·PIN에서 등록 코드를')).toBeVisible()
  await category.locator(':scope > summary').click()
  await expect(category.getByText('학부모 화면의 기기·PIN에서 등록 코드를')).not.toBeVisible()
  await dialog.locator('summary').filter({ hasText: '문의·오류 신고 안내' }).click()
  await expect(dialog.getByText('문제가 발생한 화면, 눌렀던 버튼, 발생 시각과 오류 문구를')).toBeVisible()
  await dialog.locator('summary').filter({ hasText: '개인정보 처리 동의' }).click()
  await expect(dialog.getByText('이 화면은 개발용 목업입니다.', { exact: false })).toBeVisible()
  const box = await dialog.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await expect(page.getByRole('button', { name: '이용 안내 닫기' })).toBeInViewport()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.getByRole('button', { name: '이용 안내 닫기' }).click()
  await expect(dialog).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
})

test('소개 이동과 공책 앞뒤 전환 및 시작 링크 @responsive', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.lp-thought-book')).toContainText('내 글로.')
  await page.getByRole('link', { name: '서비스 소개', exact: true }).click()
  await expect(page.locator('#about-title')).toBeInViewport()
  const steps = page.getByRole('list', { name: '학습 흐름 예시 선택' }).getByRole('button')
  await steps.nth(1).click()
  await expect(page.locator('#learning-example')).toContainText('더 말해 보기')
  await steps.nth(2).click()
  await expect(page.locator('#learning-example')).toContainText('돌아보기')
  await steps.nth(0).click()
  await expect(page.locator('#learning-example')).toContainText('오늘의 미션')
  await expect(page.locator('.lp-learning .lp-text-link')).toHaveAttribute('href', /student\/login/)
  await expect(page.locator('.lp-parent-story .lp-text-link')).toHaveAttribute('href', /login/)
})

test('제본선을 따라 글씨가 함께 넘어가고 완료 후 단계를 바꾼다 @responsive', async ({ page }) => {
  await page.goto('/')
  const book = page.locator('#learning-example')
  const steps = page.getByRole('list', { name: '학습 흐름 예시 선택' }).getByRole('button')
  await book.scrollIntoViewIfNeeded()
  const before = await book.boundingBox()
  await steps.nth(1).click()
  const leaf = page.locator('.lp-turning-leaf')
  await leaf.evaluate(el => { for (const a of el.getAnimations()) { a.pause(); a.currentTime = 300 } })
  await expect(book).toHaveAttribute('data-step', '0')
  await expect(steps.nth(2)).toBeDisabled()
  await expect(leaf.locator('.lp-leaf-front')).toContainText('우리 동네에는 도서관이 필요해요.')
  await expect(leaf.locator('.lp-leaf-back')).toContainText('도서관이 생기면 누구에게')
  await leaf.evaluate(el => el.getAnimations().forEach(a => a.finish()))
  await expect(book).toHaveAttribute('data-step', '1')
  const after = await book.boundingBox()
  expect(after!.width).toBeCloseTo(before!.width, 0)
  expect(after!.height).toBeCloseTo(before!.height, 0)
  await steps.nth(0).click()
  await expect(leaf).toHaveAttribute('data-direction', 'previous')
  await expect(book).toHaveAttribute('data-step', '0')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await steps.nth(2).click()
  await expect(book).toHaveAttribute('data-step', '2')
})
