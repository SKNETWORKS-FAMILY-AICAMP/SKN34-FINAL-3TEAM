test('제본선을 따라 글씨가 함께 넘어가고 완료 후 단계를 바꾼다 @responsive', async ({ page }) => {
  await page.goto('/')
  const book = page.locator('#learning-example')
  const steps = page.getByRole('list', { name: '학습 흐름 예시 선택' }).getByRole('button')
  await book.scrollIntoViewIfNeeded()
  const before = await book.boundingBox()
  // 브라우저 부하와 무관하게 중간 프레임을 검사한 뒤 직접 완료시킨다.
  await page.addStyleTag({ content: '.lp-turning-leaf { animation-play-state: paused !important; }' })
  await steps.nth(1).click()
  const leaf = page.locator('.lp-turning-leaf')
  await leaf.evaluate(el => { for (const a of el.getAnimations()) { a.pause(); a.currentTime = 300 } })
  await expect(book).toHaveAttribute('data-step', '0')
  await expect(steps.nth(2)).toBeDisabled()
  await expect(leaf.locator('.lp-leaf-front')).toContainText('우리 동네에는 도서관이 필요해요.')
  await expect(leaf.locator('.lp-leaf-back')).toContainText('도서관이 생기면 누구에게')
  await leaf.evaluate(el => el.getAnimations().forEach(a => a.finish()))
  await expect(book).toHaveAttribute('data-step', '1')
  const after = await book.boundingBox()
  expect(after!.width).toBeCloseTo(before!.width, 0)
  expect(after!.height).toBeCloseTo(before!.height, 0)
  await steps.nth(0).click()
  await expect(leaf).toHaveAttribute('data-direction', 'previous')
  await leaf.evaluate(el => el.getAnimations().forEach(a => a.finish()))
  await expect(book).toHaveAttribute('data-step', '0')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await steps.nth(2).click()
  await expect(book).toHaveAttribute('data-step', '2')
})


test('두 단계 이동은 목표 내용을 즉시 보여 주고 두 장을 넘긴다 @responsive', async ({ page }) => {
  await page.goto('/')
  const book = page.locator('#learning-example')
  const steps = page.getByRole('list', { name: '학습 흐름 예시 선택' }).getByRole('button')
  await page.addStyleTag({ content: '.lp-turning-leaf { animation-play-state: paused !important; }' })
  for (const [target, direction] of [[2, 'next'], [0, 'previous']] as const) {
    await steps.nth(target).click()
    const leaves = page.locator('.lp-turning-leaf')
    await expect(leaves).toHaveCount(2)
    await expect(book).toHaveAttribute('data-step', String(target))
    await expect(leaves.last().locator('.lp-leaf-back')).toContainText(target === 2 ? '처음 생각에서 무엇이 더해졌나요?' : '우리 동네에는 도서관이 필요해요.')
    await expect(leaves.first()).toHaveAttribute('data-direction', direction)
    await leaves.evaluateAll(els => els.forEach(el => el.getAnimations({ subtree: true }).forEach(a => { a.pause(); a.currentTime = 450 })))
    await expect(book).toHaveAttribute('aria-busy', 'true')
    await leaves.first().evaluate(el => el.getAnimations().forEach(a => a.finish()))
    await expect(book).toHaveAttribute('aria-busy', 'true')
    await leaves.last().evaluate(el => el.getAnimations().forEach(a => a.finish()))
    await expect(book).toHaveAttribute('data-step', String(target))
    await expect(leaves).toHaveCount(0)
  }
})

test('바다 물고기 떼는 2초 후 나타나고 포인터가 떠나면 초기화한다', async ({ page }) => {
  await page.goto('/')
  const sea = page.locator('.lp-world[data-theme="sea"]')
  await sea.hover()
  const school = sea.locator('.lp-fish-school')
  await expect(school).toHaveCount(1)
  expect(await school.evaluate(el => getComputedStyle(el).animationDelay)).toBe('2s')
  await school.evaluate(el => { const a = el.getAnimations()[0]; a.pause(); a.currentTime = 1000 })
  expect(await school.evaluate(el => Number(getComputedStyle(el).opacity))).toBe(0)
  await school.evaluate(el => { el.getAnimations()[0].currentTime = 5500 })
  expect(await school.evaluate(el => Number(getComputedStyle(el).opacity))).toBeGreaterThan(.4)
  await page.mouse.move(0, 0)
  await expect(school).toHaveCount(0)
  await sea.hover()
  expect(await school.evaluate(el => Number(getComputedStyle(el).opacity))).toBe(0)
})


