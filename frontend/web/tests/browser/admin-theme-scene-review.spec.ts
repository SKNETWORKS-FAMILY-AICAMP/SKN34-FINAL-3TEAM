import { test, expect } from '@playwright/test'

test('검수 상세에서 주간 스토리보드, 요일별 미션과 전체 이어보기를 오간다 @responsive', async ({ page }) => {
  await page.goto('/admin/login')
  await page.getByLabel('로그인 ID', { exact: true }).fill('content@example.test')
  await page.getByLabel('비밀번호', { exact: true }).fill('demo-only')
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/home/)
  await page.goto('/admin/theme-drafts?grade=G4&source=AUTO&stage=review')
  const shelf = page.getByRole('region', { name: '주간 테마 목록', exact: true })
  await expect(shelf.getByLabel('학년 선택')).toHaveValue('G4')
  await expect(shelf.getByLabel('검수 상태 선택')).toHaveValue('review')
  await expect(shelf.getByLabel('생성 출처 선택')).toHaveValue('AUTO')
  await page.getByRole('link', { name: / 상세 열기$/ }).first().click()

  await expect(page.getByRole('heading', { name: '주간 스토리보드' })).toBeVisible()
  const storyboard = page.getByRole('navigation', { name: '검수 장면 선택' })
  const scenes = storyboard.getByRole('button')
  await expect(scenes).toHaveCount(7)
  const dayNames = ['시작 영상', '월요일 장면', '화요일 장면', '수요일 장면', '목요일 장면', '금요일 장면', '종료 영상']
  for (const [i, day] of dayNames.entries()) {
    await expect(scenes.nth(i)).toHaveAccessibleName(new RegExp('^' + day))
  }
  await expect(storyboard.locator('img')).toHaveCount(7)
  const sceneTab = page.getByRole('button', { name: /^주간 장면/ })
  const missionsTab = page.getByRole('button', { name: /^요일별 미션/ })
  await expect(sceneTab).toHaveAttribute('aria-pressed', 'true')
  await expect(missionsTab).toContainText('5')
  if ((page.viewportSize()?.width ?? 0) >= 1200) {
    const boardBox = await storyboard.boundingBox()
    const playerBox = await page.locator('.tw-single').boundingBox()
    expect(boardBox!.x + boardBox!.width).toBeLessThanOrEqual(playerBox!.x)
  }
  await missionsTab.click()
  await expect(missionsTab).toHaveAttribute('aria-pressed', 'true')
  const missions = page.getByRole('region', { name: '요일별 미션', exact: true }).getByRole('listitem')
  await expect(missions).toHaveCount(5)
  const thursday = missions.filter({ hasText: '목요일' })
  await thursday.getByRole('button', { name: '내용 보기' }).click()
  await page.getByRole('dialog').getByRole('button', { name: '목요일 장면 보기' }).click()
  await expect(page).toHaveURL(/scene=THU/)
  await expect(storyboard.getByRole('button', { name: /^목요일/ })).toHaveAttribute('aria-current', /true|step/)
  await expect(sceneTab).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '전체 이어보기', exact: true }).click()
  await expect(page.getByRole('navigation', { name: '전체 재생 장면 선택' }).getByRole('button')).toHaveCount(7)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('초안 채택 후 요일별 미션을 열고 편집기에서 고정된 학년·적용 주와 테마 저장을 확인한다', async ({ page }) => {
  await page.goto('/admin/login')
  await page.getByLabel('로그인 ID', { exact: true }).fill('content@example.test')
  await page.getByLabel('비밀번호', { exact: true }).fill('demo-only')
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/home/)
  await page.goto('/admin/theme-drafts?grade=G4&source=AUTO&stage=review')
  await page.getByRole('link', { name: / 상세 열기$/ }).first().click()
  await page.getByRole('button', { name: /^(초안 채택|이 주차로 채택)$/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: '채택', exact: true }).click()
  await expect(page.getByRole('button', { name: /^요일별 미션/ })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('region', { name: '요일별 미션', exact: true }).getByRole('listitem')).toHaveCount(5)
  await expect(page.getByRole('status').filter({ hasText: '초안을 채택했습니다.' })).toBeVisible()
  await page.getByRole('link', { name: '채택한 테마 편집' }).click()
  const schedule = page.getByRole('group', { name: '채택 시 확정된 편성' })
  await expect(schedule).toContainText('초4 · 적용 주')
  await expect(page.getByLabel('학년', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('주 시작일', { exact: true })).toHaveCount(0)
  await page.getByLabel('테마 제목').fill('검수 후 수정한 제목')
  await page.getByRole('button', { name: '테마 저장' }).click()
  await expect(page.getByText('테마를 저장했습니다.', { exact: true })).toBeVisible()

  const errors = await page.evaluate(async () => {
    const { adminRetentionApi: api }: typeof import('../../src/data/admin/retentionApi.ts') = await import('/src/data/admin/retentionApi.ts' as string)
    const id = new URL(location.href).searchParams.get('themeId')!
    const theme = await api.theme(id)
    const later = new Date(theme.weekStart + 'T00:00:00Z')
    later.setUTCDate(later.getUTCDate() + 7)
    const problems = []
    for (const change of [{ grade: 'G5' as const }, { weekStart: later.toISOString().slice(0, 10) }]) {
      try {
        await api.saveTheme(id, { ...theme, ...change })
        problems.push(null)
      } catch (err) {
        const { status, code } = (err as import('../../src/data/apiClient.ts').ApiError).problem
        problems.push({ status, code })
      }
    }
    return problems
  })
  expect(errors).toEqual(Array(2).fill({ status: 409, code: 'THEME_SCHEDULE_LOCKED' }))
  await page.reload()
  await expect(schedule).toContainText('초4 · 적용 주')
  await expect(page.getByLabel('테마 제목')).toHaveValue('검수 후 수정한 제목')
})

