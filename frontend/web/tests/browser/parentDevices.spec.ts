import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/login')
  await page.getByRole('button', { name: '시연 계정으로 로그인', exact: true }).click()
  await expect(page).toHaveURL(/parent\/journal/)
}

test('device settings share family portraits and preserve PIN and pairing targets @responsive', async ({ page }, info) => {
  await login(page)
  await page.goto('/parent/devices?childId=demo-seoyun')
  await expect(page.getByRole('heading', { name: '기기 및 PIN', exact: true })).toBeVisible()
  await expect(page.getByText('아직 연결된 기기가 없습니다.')).toBeVisible()
  await page.screenshot({ path: info.outputPath('devices-empty.png'), fullPage: true })
  await page.getByRole('button', { name: '서윤 뭉치 변경' }).click()
  let dialog = page.getByRole('dialog', { name: '서윤 뭉치 변경' })
  await dialog.getByRole('button', { name: '꽃잎뭉치', exact: true }).click()
  await dialog.getByRole('button', { name: '뭉치 저장', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '서윤 뭉치 변경' }).locator('svg[data-friend]')).toHaveAttribute('data-friend', 'petal')
  await page.goto('/parent/settings?childId=demo-seoyun')
  await expect(page.getByRole('article', { name: '서윤 자녀 카드' }).locator('svg[data-friend]')).toHaveAttribute('data-friend', 'petal')
  await page.goto('/parent/devices?childId=demo-seoyun')
  await page.getByRole('button', { name: '서윤 PIN 관리' }).click()
  dialog = page.getByRole('dialog', { name: '서윤 PIN 관리' })
  await dialog.getByLabel('서윤 새 PIN', { exact: true }).fill('2468')
  await dialog.getByLabel('서윤 새 PIN 확인', { exact: true }).fill('2469')
  await dialog.getByRole('button', { name: 'PIN 정하기', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('두 번 입력한 PIN이 다릅니다.')
  await dialog.getByLabel('서윤 새 PIN 확인', { exact: true }).fill('2468')
  const pinRequest = page.waitForRequest(r => r.url().endsWith('/children/demo-seoyun/pin') && r.method() === 'PUT')
  await dialog.getByRole('button', { name: 'PIN 정하기', exact: true }).click()
  expect((await pinRequest).postDataJSON()).toEqual({ pin: '2468' })
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('서윤의 PIN을 저장했습니다.')
  await expect(page.getByRole('button', { name: '서윤 PIN 관리' })).toBeFocused()
  await page.screenshot({ path: info.outputPath('devices-pin.png') })
  await page.keyboard.press('Escape')
  await expect(page.locator('.device-child-list').getByText('PIN 설정 완료')).toBeVisible()
  await page.getByRole('button', { name: '기기 연결', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '새 학습 기기 연결' })
  await dialog.getByRole('checkbox', { name: /도윤/ }).uncheck()
  const pairingRequest = page.waitForRequest(r => r.url().endsWith('/student-devices/pairings') && r.method() === 'POST')
  await dialog.getByRole('button', { name: '등록 코드 만들기', exact: true }).click()
  expect((await pairingRequest).postDataJSON()).toEqual({ childIds: ['demo-seoyun'] })
  await expect(dialog.getByRole('img', { name: /자녀 기기 등록 QR/ })).toBeVisible()
  await page.screenshot({ path: info.outputPath('devices-pairing.png') })
  await dialog.getByRole('link', { name: '등록 화면 열기' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('devices-pairing-code.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('device management shows server records and requires explicit revoke confirmation @responsive', async ({ page }, info) => {
  await login(page)
  await page.evaluate(() => sessionStorage.setItem('sagomungchi:msw-device:v1', JSON.stringify({
    pins: {}, pairings: {}, currentDeviceId: null,
    devices: [{ deviceId: 'fixture-device', label: '가족 학습 태블릿', owner: 'parent@example.test', childIds: ['demo-seoyun'], createdAt: '2026-11-01T00:00:00Z', lastUsedAt: '2026-11-25T07:30:00Z', expiresAt: '2026-12-25T07:30:00Z', revokedAt: null }],
  })))
  const deletions: string[] = []
  page.on('request', r => { if (r.method() === 'DELETE') deletions.push(r.url()) })
  await page.goto('/parent/devices?childId=demo-seoyun')
  await expect(page.getByText('가족 학습 태블릿', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '가족 학습 태블릿 기기 관리' }).click()
  await expect(page.getByText('마지막 사용', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '가족 학습 태블릿 등록 해제' }).click()
  const confirmation = page.getByRole('group', { name: '가족 학습 태블릿 해제 확인' })
  await confirmation.getByRole('button', { name: '취소', exact: true }).focus()
  await confirmation.evaluate(el => el.scrollIntoView({ block: 'center' }))
  await page.screenshot({ path: info.outputPath('devices-confirm.png') })
  await page.screenshot({ path: info.outputPath('devices-confirm-viewport.png') })
  await confirmation.getByRole('button', { name: '취소', exact: true }).click()
  expect(deletions).toHaveLength(0)
  await page.getByRole('button', { name: '가족 학습 태블릿 등록 해제' }).click()
  await confirmation.getByRole('button', { name: '해제', exact: true }).click()
  await expect(page.getByText('아직 연결된 기기가 없습니다.')).toBeVisible()
  expect(deletions).toHaveLength(1)
})
